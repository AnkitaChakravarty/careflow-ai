def _qa(messages, tools):
    import re
    tool_msgs = [m for m in messages if isinstance(m, dict) and m.get("role") == "tool"]
    if not tool_msgs:
        m = re.search(r"patient_id (\d+)", messages[-1]["content"])
        pid = int(m.group(1)) if m else 1
        tc = SimpleNamespace(id="call_1", type="function",
                             function=SimpleNamespace(name="get_observations", arguments=json.dumps({"patient_id": pid, "last_n": 3})))
        return _msg(None, [tc]), (1100, 0, 30)
    vit = json.loads(tool_msgs[-1]["content"])
    if isinstance(vit, dict):
        return _msg("Not documented in the record (mock answer)."), (1400, 1024, 20)
    lines = [f"- {v['ts']}: BP {v.get('sbp')}/{v.get('dbp')}, HR {v.get('hr')} [{v['cite']}]" for v in vit]
    return _msg("Latest observations (mock answer):\n" + "\n".join(lines)), (1600, 1024, 120)


def _draft(messages, tools):
    rec = json.loads(messages[-1]["content"].split("PATIENT RECORD JSON:\n", 1)[1])
    v = rec["observations"][-1] if rec["observations"] else None
    sections = [{"heading": "Situation", "text": f"{rec['patient']['name']}, bed {rec['patient']['bed']}."},
                {"heading": "Assessment", "text": (f"Latest observation recorded [{v['cite']}]." if v else "Not documented.")},
                {"heading": "Uncertain or unverified items", "text": "Mock draft - not generated by a model."}]
    return _msg(json.dumps({"sections": sections})), (3500, 0, 600)


